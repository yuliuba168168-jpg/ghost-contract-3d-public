def clean(body):
    body = re.sub(r'\[[^\]]*\]', '', body)
    body = re.sub(r'[（(][\u4e00-\u9fff]{2,4}[）)]', '', body)
    ps = [p.strip().replace('鬼蜮', '鬼域') for p in body.split('\n') if p.strip()]
    bad = set()
    for i, p in enumerate(ps):
        if BLOCK.search(p): bad.update(range(max(0, i - 3), min(len(ps), i + 4)))
    safe = [p for i, p in enumerate(ps) if i not in bad and not JUNK.search(p) and not re.match(r'^第\d+章', p)]
    merged, buf = [], ''
    for p in safe:
        buf += p
        if len(buf) >= 60: merged.append(buf); buf = ''
    if buf: merged.append(buf)
    if len(''.join(merged)) <= 950: return '\n\n'.join(merged)
    n = len(merged); thirds = [merged[:max(1, n // 3)], merged[n // 3:2 * n // 3], merged[2 * n // 3:]]
    chunks = []
    for group in thirds:
        sel, size = [], 0
        for p in group:
            if size + len(p) > 350 and sel: break
            sel.append(p); size += len(p)
        chunks.append('\n\n'.join(sel))
    return '\n\n〔本章节选，略去中间过渡〕\n\n'.join(chunks)

